import test from 'node:test';
import assert from 'node:assert/strict';
import { XteaCustom, createLegacyInitializationVector } from '../src/crypto/xtea-custom.js';
import { generateEncryptionKey } from '../src/crypto/encryption-key.js';
import { encodeVarint, decodeVarint, encodeVarintField, encodeBytesField, decodeProtobufFields } from '../src/protocol/protobuf.js';
import { LoginPrepareRequest, LoginRequest, LoginTokenGetRequest, EmptyPacket } from '../src/protocol/requests.js';
import { buildPacket, buildFullyEncryptedPacket } from '../src/protocol/packets.js';
import { decodePacket } from '../src/protocol/responses.js';
import cipherFixtures from './fixtures/python-vectors.json' with { type: 'json' };
import packetFixtures from './fixtures/python-packets.json' with { type: 'json' };

const cipherKey = Buffer.from(cipherFixtures.encryption_key_hex, 'hex');
const fixedInitializationVector = Buffer.from(cipherFixtures.initialization_vector_hex, 'hex');

test('custom XTEA encryption/decryption matches the Python byte-level fixtures', () => {
    const cipher = new XteaCustom(cipherKey);
    for (const fixture of cipherFixtures.vectors) {
        const plaintext = Buffer.from(fixture.plaintext_hex, 'hex');
        const ciphertext = cipher.encrypt(plaintext, fixedInitializationVector);
        assert.equal(ciphertext.toString('hex'), fixture.ciphertext_hex);
        assert.deepEqual(cipher.decrypt(ciphertext), plaintext);
        assert.deepEqual(cipher.decrypt(Buffer.from(fixture.ciphertext_hex, 'hex')), plaintext);
    }
});

test('short plaintext now handles the original Python uninitialized-leftover bug', () => {
    const cipher = new XteaCustom(cipherKey);
    for (let length = 0; length < 8; length += 1) {
        const input = Buffer.alloc(length, 0x61);
        assert.deepEqual(cipher.decrypt(cipher.encrypt(input, fixedInitializationVector)), input);
    }
});

test('key derivation matches the Python fixture', () => {
    const fixture = cipherFixtures.derived_key;
    assert.equal(generateEncryptionKey(fixture.password, fixture.salt, fixture.verify_code).toString('hex'), fixture.key_hex);
});

test('legacy lrand48 returns repeatable initialization vectors', () => {
    assert.equal(
        createLegacyInitializationVector(1700000000).toString('hex'),
        createLegacyInitializationVector(1700000000).toString('hex'),
    );
    assert.notEqual(
        createLegacyInitializationVector(1700000001).toString('hex'),
        createLegacyInitializationVector(1700000000).toString('hex'),
    );
});

test('protobuf varint handles 64-bit unsigned integer values losslessly', () => {
    for (const input of [0n, 1n, 127n, 128n, 300n, 123456789012345n, (1n << 64n) - 1n]) {
        const encoded = encodeVarint(input);
        const decoded = decodeVarint(encoded, 0);
        assert.equal(decoded.value, input);
        assert.equal(decoded.offset, encoded.length);
    }
    assert.throws(() => decodeVarint(Buffer.from([0x80]), 0));
    assert.throws(() => decodeProtobufFields(Buffer.from([0x0a, 0x05, 0x01])));
});

test('all four packet formats exactly match Python-generated bytes', () => {
    const options = {
        deviceIdentifier: packetFixtures.params.deviceIdentifier,
        timestamp: packetFixtures.params.timestamp,
        randomKey: Buffer.from(packetFixtures.params.randomKey, 'hex'),
        initializationVector: Buffer.from(packetFixtures.params.initializationVector, 'hex'),
    };
    const generatedPackets = {
        prepare_packet_hex: new LoginPrepareRequest(packetFixtures.account, options).buildFullPacket(),
        login_packet_hex: new LoginRequest(packetFixtures.password, packetFixtures.params.randomKey, options).buildFullPacket(),
        token_packet_hex: new LoginTokenGetRequest(packetFixtures.params.randomKey, options).buildFullPacket(),
        empty_packet_hex: new EmptyPacket(packetFixtures.params.randomKey, 442, options).buildFullPacket(),
    };
    for (const [fixtureKey, packet] of Object.entries(generatedPackets)) {
        assert.equal(packet.toString('hex'), packetFixtures[fixtureKey], fixtureKey);
    }
});

test('response decoder can parse plaintext headers and fully encrypted payloads', () => {
    const header = Buffer.concat([
        encodeVarintField(1, 285212918),
        encodeVarintField(3, 3),
        encodeVarintField(4, 442),
        encodeVarintField(5, 0),
    ]);
    const body = encodeBytesField(1, Buffer.from('example-sso-key'));
    const plaintextPacket = buildPacket(header, body);
    const encryptedPacket = buildFullyEncryptedPacket(plaintextPacket.subarray(4), cipherKey, {
        initializationVector: fixedInitializationVector,
    });
    for (const packet of [plaintextPacket, encryptedPacket]) {
        const result = decodePacket(packet, cipherKey);
        assert.equal(result.header.result, 0);
        assert.equal(result.message_type, 'SsoKeyGetReply');
        assert.equal(result.body.sso_key, 'example-sso-key');
    }
});

test('header framing and duplicate protobuf fields decode as expected', () => {
    const message = Buffer.concat([encodeVarintField(1, 1), encodeVarintField(1, 2)]);
    assert.equal(decodeProtobufFields(message).get(1).value, 2n);
    const frame = Buffer.from(packetFixtures.prepare_packet_hex, 'hex');
    assert.equal(frame.readUInt32LE(0), frame.length - 4);
    assert.equal(decodePacket(frame).header.command, 256);
    assert.throws(() => decodePacket(Buffer.from([4, 0, 0, 0, 0, 0])), /framing length mismatch/);
});
